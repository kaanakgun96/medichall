do $schedule$
declare
  existing_job bigint;
  scheduled_job bigint;
begin
  if exists (
    select 1
    from pg_extension
    where extname = 'pg_cron'
  ) then
    execute
      'select jobid from cron.job where jobname = $1 limit 1'
      into existing_job
      using 'medichall-matchmaking-automation';
    if existing_job is not null then
      execute 'select cron.unschedule($1)' using existing_job;
    end if;
    execute
      'select cron.schedule($1, $2, $3)'
      into scheduled_job
      using
        'medichall-matchmaking-automation',
        '*/5 * * * *',
        'select public.process_matchmaking_automation(200);';
    raise notice 'Scheduled matchmaking automation job %', scheduled_job;
  else
    raise notice
      'pg_cron is unavailable; process_matchmaking_automation remains callable by service role';
  end if;
exception
  when insufficient_privilege or undefined_table or invalid_schema_name then
    raise notice
      'Matchmaking automation was not scheduled: %',
      sqlerrm;
end
$schedule$;

notify pgrst, 'reload schema';

commit;
