create or replace function public.process_matchmaking_automation(
  p_limit integer default 200
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $function$
declare
  safe_limit integer := greatest(1, least(coalesce(p_limit, 200), 1000));
  expired_meeting record;
  due_reminder record;
  expired_count integer := 0;
  reminder_count integer := 0;
  other_profile_id uuid;
  reminder_connection_id bigint;
  reminder_video_status text;
  notification_title text;
  notification_body text;
begin
  if not public.mm_has_service_role() then
    raise exception 'Service role required'
      using errcode = '42501';
  end if;

  for expired_meeting in
    with candidates as (
      select meeting.id, meeting.status as previous_status
      from public.matchmaking_meeting_requests meeting
      where meeting.status in (
        'proposed',
        'awaiting_response',
        'counter_proposed'
      )
        and (
          meeting.expires_at <= now()
          or not exists (
            select 1
            from public.matchmaking_meeting_proposals proposal
            where proposal.meeting_id = meeting.id
              and proposal.proposal_round = meeting.proposal_round
              and proposal.status = 'active'
              and proposal.end_at > now()
          )
        )
      order by meeting.expires_at nulls last, meeting.id
      limit safe_limit
      for update skip locked
    )
    update public.matchmaking_meeting_requests meeting
    set
      status = 'expired',
      state_version = state_version + 1,
      last_activity_at = now(),
      updated_at = now()
    from candidates
    where meeting.id = candidates.id
    returning meeting.*, candidates.previous_status
  loop
    update public.matchmaking_meeting_proposals
    set status = 'withdrawn'
    where meeting_id = expired_meeting.id
      and status = 'active';

    perform public.mm_add_meeting_event(
      expired_meeting.id,
      expired_meeting.connection_id,
      null,
      'meeting_expired',
      expired_meeting.previous_status,
      'expired',
      jsonb_build_object('automation', true)
    );
    perform public.mm_add_system_message(
      expired_meeting.connection_id,
      'The meeting proposal expired without a confirmed time.',
      jsonb_build_object(
        'event_type', 'meeting_expired',
        'meeting_id', expired_meeting.id
      )
    );

    perform public.mm_add_notification(
      expired_meeting.requester_profile_id,
      null,
      expired_meeting.connection_id,
      expired_meeting.id,
      'meeting_expired',
      'Meeting proposal expired',
      'The proposed meeting times expired without confirmation.',
      'meeting:' || expired_meeting.id || ':expired',
      '#matchmaking-meeting=' || expired_meeting.id
    );
    perform public.mm_add_notification(
      expired_meeting.recipient_profile_id,
      null,
      expired_meeting.connection_id,
      expired_meeting.id,
      'meeting_expired',
      'Meeting proposal expired',
      'The proposed meeting times expired without confirmation.',
      'meeting:' || expired_meeting.id || ':expired',
      '#matchmaking-meeting=' || expired_meeting.id
    );
    expired_count := expired_count + 1;
  end loop;

  for due_reminder in
    with candidates as (
      select reminder.id
      from public.matchmaking_meeting_reminders reminder
      where reminder.status = 'scheduled'
        and reminder.due_at <= now()
      order by reminder.due_at, reminder.id
      limit safe_limit
      for update skip locked
    )
    update public.matchmaking_meeting_reminders reminder
    set status = 'processing', claimed_at = now()
    from candidates
    where reminder.id = candidates.id
    returning reminder.*
  loop
    if due_reminder.channel = 'in_app' then
      notification_title := case due_reminder.reminder_type
        when 'meeting_24h' then 'Meeting tomorrow'
        when 'meeting_15m' then 'Meeting starts in 15 minutes'
        when 'meeting_start' then 'Meeting starting now'
        else 'Meeting follow-up'
      end;
      select
        case
          when meeting.requester_profile_id = due_reminder.recipient_profile_id
            then meeting.recipient_profile_id
          else meeting.requester_profile_id
        end,
        meeting.connection_id,
        meeting.video_status
      into
        other_profile_id,
        reminder_connection_id,
        reminder_video_status
      from public.matchmaking_meeting_requests meeting
      where meeting.id = due_reminder.meeting_id;

      notification_body := case due_reminder.reminder_type
        when 'meeting_24h' then 'Review the agenda and confirmed time.'
        when 'meeting_15m' then case
          when reminder_video_status = 'ready'
            then 'Your secure meeting room is now available.'
          else 'Open the meeting workspace; embedded video is not configured.'
        end
        when 'meeting_start' then case
          when reminder_video_status = 'ready'
            then 'Open the meeting workspace to join securely.'
          else 'Your meeting starts now; embedded video is not configured.'
        end
        else 'Record the outcome and next steps from your meeting.'
      end;

      perform public.mm_add_notification(
        due_reminder.recipient_profile_id,
        other_profile_id,
        reminder_connection_id,
        due_reminder.meeting_id,
        due_reminder.reminder_type,
        notification_title,
        notification_body,
        due_reminder.dedupe_key,
        '#matchmaking-meeting=' || due_reminder.meeting_id
      );

      update public.matchmaking_meeting_reminders
      set status = 'sent', sent_at = now(), error_code = null
      where id = due_reminder.id;
      reminder_count := reminder_count + 1;
    else
      update public.matchmaking_meeting_reminders
      set
        status = 'failed',
        error_code = 'email_provider_unconfigured'
      where id = due_reminder.id;
    end if;
  end loop;

  delete from public.matchmaking_idempotency_keys
  where expires_at < now();

  delete from public.matchmaking_video_access_log
  where created_at < now() - interval '30 days';

  return jsonb_build_object(
    'expired_meetings', expired_count,
    'sent_in_app_reminders', reminder_count,
    'processed_at', now()
  );
end;
$function$;

