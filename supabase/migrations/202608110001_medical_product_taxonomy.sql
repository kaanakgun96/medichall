create or replace function public.mm_taxonomy_product_compatibility_v1(
  p_source_profile_id uuid,
  p_target_profile_id uuid
)
returns jsonb
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $function$
declare
  source_profile public.matchmaking_profiles%rowtype;
  target_profile public.matchmaking_profiles%rowtype;
  offered_profile uuid;
  interested_profile uuid;
  best_score integer := 0;
  evidence jsonb := '[]'::jsonb;
  offered_count integer := 0;
  interested_count integer := 0;
begin
  select * into source_profile from public.matchmaking_profiles
  where id = p_source_profile_id and is_active;
  select * into target_profile from public.matchmaking_profiles
  where id = p_target_profile_id and is_active;
  if source_profile.id is null or target_profile.id is null then
    return jsonb_build_object('available', false, 'score', 0, 'matches', '[]'::jsonb);
  end if;
  if source_profile.role = 'manufacturer' then
    offered_profile := source_profile.id;
    interested_profile := target_profile.id;
  else
    offered_profile := target_profile.id;
    interested_profile := source_profile.id;
  end if;

  with offered as (
    select interest.taxonomy_id, taxonomy.canonical_name,
      'profile'::text source, interest.mapping_source
    from public.matchmaking_taxonomy_interests interest
    join public.medical_product_taxonomy taxonomy
      on taxonomy.id = interest.taxonomy_id and taxonomy.is_active
    where interest.profile_id = offered_profile
      and interest.interest_kind = 'offered'
      and interest.resolution_status = 'mapped'
    union
    select mapping.taxonomy_id, taxonomy.canonical_name,
      'company_product', mapping.mapping_source
    from public.matchmaking_profiles profile
    join public.products product on product.company_id = profile.company_id
      and product.is_active
    join public.product_taxonomy_mappings mapping on mapping.product_id = product.id
      and mapping.status = 'approved' and mapping.is_primary
    join public.medical_product_taxonomy taxonomy
      on taxonomy.id = mapping.taxonomy_id and taxonomy.is_active
    where profile.id = offered_profile
  ), interested as (
    select interest.taxonomy_id, taxonomy.canonical_name,
      interest.selection_scope, interest.mapping_source
    from public.matchmaking_taxonomy_interests interest
    join public.medical_product_taxonomy taxonomy
      on taxonomy.id = interest.taxonomy_id and taxonomy.is_active
    where interest.profile_id = interested_profile
      and interest.interest_kind = 'interested'
      and interest.resolution_status = 'mapped'
  ), pairs as (
    select offered.taxonomy_id offered_id,
      offered.canonical_name offered_name,
      interested.taxonomy_id interested_id,
      interested.canonical_name interested_name,
      interested.selection_scope,
      offered.source,
      public.medical_taxonomy_pair_score_v1(
        offered.taxonomy_id, interested.taxonomy_id
      ) pair_score
    from offered cross join interested
  ), ranked as (
    select *, row_number() over (
      partition by offered_id order by pair_score desc, interested_id
    ) rank_for_offer
    from pairs where pair_score > 0
  )
  select
    coalesce((select max(pair_score) from pairs), 0),
    coalesce((select count(*) from offered), 0),
    coalesce((select count(*) from interested), 0),
    coalesce((select jsonb_agg(jsonb_build_object(
      'offered_taxonomy_id', offered_id,
      'offered_name', offered_name,
      'interested_taxonomy_id', interested_id,
      'interested_name', interested_name,
      'relationship', case pair_score
        when 100 then 'exact_category'
        when 75 then 'broad_family'
        when 25 then 'related_sibling'
        else 'same_family_weak'
      end,
      'score', pair_score,
      'source', source
    ) order by pair_score desc, offered_name) from ranked
      where rank_for_offer = 1 and pair_score >= 25), '[]'::jsonb)
  into best_score, offered_count, interested_count, evidence;

  return jsonb_build_object(
    'available', offered_count > 0 and interested_count > 0,
    'score', best_score,
    'offered_count', offered_count,
    'interested_count', interested_count,
    'matches', evidence,
    'summary', case
      when best_score = 100 then 'Exact medical-product taxonomy categories align.'
      when best_score = 75 then 'A broad product-family interest includes the supplied category.'
      when best_score >= 25 then 'Related product categories need qualification.'
      when offered_count = 0 or interested_count = 0 then 'Structured product taxonomy data is incomplete.'
      else 'The selected product families do not overlap.'
    end,
    'scoring', jsonb_build_object(
      'exact_category', 100,
      'parent_or_child', 75,
      'sibling_category', 25,
      'same_family_distant', 10,
      'unrelated_family', 0
    )
  );
end;
$function$;

-- Preserve the established 40/20/15/15/10 weighting while replacing only the
