-- Deterministic high-confidence backfill of existing matchmaking phrases.
with legacy_terms as (
  select profile.id as profile_id, 'offered'::text as interest_kind, term
  from public.matchmaking_profiles profile, unnest(profile.offered_products) term
  union all
  select profile.id, 'interested', term
  from public.matchmaking_profiles profile, unnest(profile.interested_products) term
), resolved as (
  select distinct on (legacy.profile_id, legacy.interest_kind, normalized.normalized_term)
    legacy.profile_id,
    legacy.interest_kind,
    alias.taxonomy_id,
    taxonomy.node_type,
    legacy.term,
    alias.confidence,
    normalized.normalized_term
  from legacy_terms legacy
  cross join lateral (
    select public.normalize_medical_product_term(legacy.term) as normalized_term
  ) normalized
  join public.medical_product_aliases alias
    on alias.normalized_alias = normalized.normalized_term
   and alias.is_active and alias.verification_status = 'approved'
   and alias.confidence >= .95
  join public.medical_product_taxonomy taxonomy
    on taxonomy.id = alias.taxonomy_id and taxonomy.is_active
  order by legacy.profile_id, legacy.interest_kind, normalized.normalized_term,
    alias.confidence desc, alias.id
)
insert into public.matchmaking_taxonomy_interests (
  profile_id, interest_kind, taxonomy_id, selection_scope,
  resolution_status, mapping_source, confidence
)
select profile_id, interest_kind, taxonomy_id, node_type,
  'mapped', 'legacy_backfill', confidence
from resolved
on conflict do nothing;

-- Unmapped historical phrases enter review without being reclassified.
with legacy_terms as (
  select profile.company_id, term
  from public.matchmaking_profiles profile,
    unnest(profile.offered_products || profile.interested_products || profile.product_categories) term
), unresolved as (
  select company_id,
    public.normalize_medical_product_term(term) normalized_term,
    min(term) sample_term,
    count(*)::integer occurrence_count
  from legacy_terms legacy
  where length(public.normalize_medical_product_term(term)) >= 2
    and not exists (
      select 1 from public.medical_product_taxonomy taxonomy
      where taxonomy.normalized_name = public.normalize_medical_product_term(term)
        and taxonomy.is_active
    )
    and not exists (
      select 1 from public.medical_product_aliases alias
      where alias.normalized_alias = public.normalize_medical_product_term(term)
        and alias.is_active and alias.verification_status = 'approved'
    )
  group by company_id, public.normalize_medical_product_term(term)
)
insert into public.medical_product_taxonomy_review_queue (
  normalized_term, sample_term, source_context, company_id, occurrence_count,
  metadata
)
select normalized_term, sample_term, 'matchmaking_custom', company_id,
  occurrence_count, jsonb_build_object('source', 'legacy_backfill')
from unresolved
on conflict (normalized_term, source_context, company_id) do update
set occurrence_count = greatest(
  public.medical_product_taxonomy_review_queue.occurrence_count,
  excluded.occurrence_count
), last_seen_at = now();

-- Public taxonomy search and deterministic resolver.
create or replace function public.search_medical_product_taxonomy_v1(
  p_query text default null,
  p_limit integer default 40
)
returns table (
  id bigint,
  parent_id bigint,
  hierarchy_level smallint,
  node_type text,
  canonical_name text,
  slug text,
  description text,
  aliases jsonb,
  match_quality numeric
)
language sql
stable
security definer
set search_path = public, pg_temp
as $function$
  with candidates as (
    select taxonomy.*,
      greatest(
        case when nullif(public.normalize_medical_product_term(p_query), '') is null then 1
             when taxonomy.normalized_name = public.normalize_medical_product_term(p_query) then 1
             when taxonomy.normalized_name like '%' || public.normalize_medical_product_term(p_query) || '%' then .9
             else public.medical_product_term_similarity(p_query, taxonomy.canonical_name)
        end,
        coalesce((
          select max(case
            when alias.normalized_alias = public.normalize_medical_product_term(p_query) then alias.confidence
            when alias.normalized_alias like '%' || public.normalize_medical_product_term(p_query) || '%' then alias.confidence * .9
            else public.medical_product_term_similarity(p_query, alias.alias_text) * alias.confidence
          end)
          from public.medical_product_aliases alias
          where alias.taxonomy_id = taxonomy.id
            and alias.is_active and alias.verification_status = 'approved'
        ), 0)
      )::numeric as quality
    from public.medical_product_taxonomy taxonomy
    where taxonomy.is_active
  )
  select candidate.id, candidate.parent_id, candidate.hierarchy_level,
    candidate.node_type, candidate.canonical_name, candidate.slug,
    candidate.description,
    coalesce((
      select jsonb_agg(alias.alias_text order by alias.alias_text)
      from public.medical_product_aliases alias
      where alias.taxonomy_id = candidate.id
        and alias.is_active and alias.verification_status = 'approved'
    ), '[]'::jsonb),
    round(candidate.quality, 4)
  from candidates candidate
  where nullif(public.normalize_medical_product_term(p_query), '') is null
     or candidate.quality >= .2
  order by candidate.quality desc, candidate.hierarchy_level, candidate.sort_order,
    candidate.canonical_name
  limit greatest(1, least(coalesce(p_limit, 40), 100));
$function$;

create or replace function public.resolve_medical_product_term_v1(
  p_term text,
  p_limit integer default 5
)
returns jsonb
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $function$
declare
  normalized_term text := public.normalize_medical_product_term(p_term);
  candidates jsonb := '[]'::jsonb;
  best record;
  resolution text := 'unmapped';
begin
  if length(normalized_term) < 2 or length(coalesce(p_term, '')) > 500 then
    raise exception 'Use a product description between 2 and 500 characters'
      using errcode = '22023';
  end if;

  select * into best
  from public.search_medical_product_taxonomy_v1(p_term, greatest(1, least(p_limit, 10)))
  order by match_quality desc, hierarchy_level desc
  limit 1;

  select coalesce(jsonb_agg(jsonb_build_object(
    'canonical_taxonomy_id', candidate.id,
    'canonical_name', candidate.canonical_name,
    'parent_id', candidate.parent_id,
    'node_type', candidate.node_type,
    'confidence', candidate.match_quality,
    'source_text', p_term,
    'source', case
      when candidate.match_quality = 1 then 'exact_or_verified_alias'
      else 'deterministic_normalized_name'
    end
  ) order by candidate.match_quality desc), '[]'::jsonb)
  into candidates
  from public.search_medical_product_taxonomy_v1(
    p_term, greatest(1, least(p_limit, 10))
  ) candidate;

  resolution := case
    when best.match_quality >= .95 then 'high_confidence'
    when best.match_quality >= .65 then 'medium_confidence'
    else 'unmapped'
  end;

  return jsonb_build_object(
    'source_text', p_term,
    'normalized_source_text', normalized_term,
    'resolution', resolution,
    'recommended', case when resolution = 'unmapped' then null else
      jsonb_build_object(
        'canonical_taxonomy_id', best.id,
        'canonical_name', best.canonical_name,
        'node_type', best.node_type,
        'confidence', best.match_quality,
        'reasoning', case
          when best.match_quality = 1 then 'Exact canonical name or approved alias.'
          else 'Deterministic normalized-term similarity; user confirmation required.'
        end,
        'source_text', p_term
      ) end,
    'alternatives', candidates,
    'semantic_provider_used', false
  );
end;
$function$;

create or replace function public.save_matchmaking_taxonomy_interests_v1(
  p_profile_id uuid,
  p_interests jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $function$
declare
  item jsonb;
  profile public.matchmaking_profiles%rowtype;
  taxonomy public.medical_product_taxonomy%rowtype;
  safe_kind text;
  safe_custom text;
  inserted_count integer := 0;
begin
  if auth.uid() is null then
    raise exception 'Authentication required' using errcode = '42501';
  end if;
  select * into profile from public.matchmaking_profiles
  where id = p_profile_id and user_id = auth.uid();
  if profile.id is null then
    raise exception 'Matchmaking profile not found or access denied'
      using errcode = '42501';
  end if;
  if jsonb_typeof(p_interests) <> 'array' or jsonb_array_length(p_interests) > 40 then
    raise exception 'Provide an array of at most 40 taxonomy interests'
      using errcode = '22023';
  end if;

  delete from public.matchmaking_taxonomy_interests
  where profile_id = p_profile_id;

  for item in select value from jsonb_array_elements(p_interests)
  loop
    safe_kind := item ->> 'interest_kind';
    if safe_kind not in ('offered', 'interested') then
      raise exception 'Each taxonomy interest needs offered or interested kind'
        using errcode = '22023';
    end if;
    if nullif(item ->> 'taxonomy_id', '') is not null then
      select * into taxonomy from public.medical_product_taxonomy
      where id = (item ->> 'taxonomy_id')::bigint and is_active;
      if taxonomy.id is null then
        raise exception 'Selected taxonomy node is unavailable'
          using errcode = '22023';
      end if;
      insert into public.matchmaking_taxonomy_interests (
        profile_id, interest_kind, taxonomy_id, selection_scope,
        resolution_status, mapping_source, confidence
      ) values (
        p_profile_id, safe_kind, taxonomy.id, taxonomy.node_type,
        'mapped', 'user_selected', 1
      ) on conflict do nothing;
    else
      safe_custom := trim(coalesce(item ->> 'custom_term', ''));
      if length(safe_custom) not between 2 and 240 then
        raise exception 'Custom product descriptions must be 2 to 240 characters'
          using errcode = '22023';
      end if;
      insert into public.matchmaking_taxonomy_interests (
        profile_id, interest_kind, custom_term, selection_scope,
        resolution_status, mapping_source
      ) values (
        p_profile_id, safe_kind, safe_custom, 'custom', 'custom', 'custom'
      ) on conflict do nothing;
      insert into public.medical_product_taxonomy_review_queue (
        normalized_term, sample_term, source_context, company_id, metadata
      ) values (
        public.normalize_medical_product_term(safe_custom), safe_custom,
        'matchmaking_custom', profile.company_id,
        jsonb_build_object('profile_id', profile.id)
      ) on conflict (normalized_term, source_context, company_id) do update
      set occurrence_count = public.medical_product_taxonomy_review_queue.occurrence_count + 1,
          last_seen_at = now(), sample_term = excluded.sample_term;
    end if;
    inserted_count := inserted_count + 1;
  end loop;

  return jsonb_build_object(
    'profile_id', p_profile_id,
    'saved_count', inserted_count,
    'provider_calls', 0
  );
end;
$function$;

