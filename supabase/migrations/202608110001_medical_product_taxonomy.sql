language plpgsql
security definer
set search_path = public, pg_temp
as $function$
declare
  source_profile public.matchmaking_profiles;
  target_profile public.matchmaking_profiles;
  taxonomy_result jsonb;
  taxonomy_value integer;
  legacy_product_value integer;
  product_value integer;
  geography_value integer;
  role_value integer;
  certification_value integer;
  commercial_value integer;
  total_value integer;
  processed integer := 0;
begin
  select * into source_profile
  from public.matchmaking_profiles
  where id = p_profile_id and user_id = auth.uid();
  if source_profile.id is null then
    raise exception 'Matchmaking profile not found or access denied';
  end if;

  for target_profile in
    select * from public.matchmaking_profiles
    where is_active = true and id <> source_profile.id
  loop
    if source_profile.role = 'manufacturer' then
      legacy_product_value := public.mm_overlap_score(
        source_profile.offered_products || source_profile.product_categories,
        target_profile.interested_products || target_profile.product_categories
      );
    else
      legacy_product_value := public.mm_overlap_score(
        source_profile.interested_products || source_profile.product_categories,
        target_profile.offered_products || target_profile.product_categories
      );
    end if;
    taxonomy_result := public.mm_taxonomy_product_compatibility_v1(
      source_profile.id, target_profile.id
    );
    taxonomy_value := coalesce((taxonomy_result ->> 'score')::integer, 0);
    product_value := case
      when coalesce((taxonomy_result ->> 'available')::boolean, false)
        then greatest(taxonomy_value, legacy_product_value)
      else legacy_product_value
    end;

    geography_value := greatest(
      public.mm_overlap_score(source_profile.target_countries,
        target_profile.served_countries || array[target_profile.country]),
      public.mm_overlap_score(source_profile.served_countries || array[source_profile.country],
        target_profile.target_countries)
    );
    role_value := public.mm_role_fit(source_profile.role, target_profile.role,
      source_profile.partner_types_sought);
    if source_profile.role = 'manufacturer' then
      certification_value := public.mm_overlap_score(
        source_profile.certifications, target_profile.required_certifications);
    else
      certification_value := public.mm_overlap_score(
        source_profile.required_certifications, target_profile.certifications);
    end if;
    commercial_value := public.mm_commercial_score(source_profile, target_profile);
    total_value := round(product_value * .40 + geography_value * .20
      + role_value * .15 + certification_value * .10
      + commercial_value * .15)::integer;

    insert into public.matchmaking_matches (
      source_profile_id, target_profile_id, match_score, confidence_level,
      product_score, geography_score, partner_type_score, certification_score,
      commercial_score, reasons, risks, generated_at, updated_at
    ) values (
      source_profile.id, target_profile.id, total_value,
      case when source_profile.profile_completeness >= 75
             and target_profile.profile_completeness >= 75 then 'high'
           when source_profile.profile_completeness >= 45
             and target_profile.profile_completeness >= 45 then 'medium'
           else 'low' end,
      product_value, geography_value, role_value, certification_value,
      commercial_value,
      jsonb_strip_nulls(jsonb_build_object(
        'products', case
          when taxonomy_value >= 75 then taxonomy_result ->> 'summary'
          when product_value >= 70 then 'Product needs and portfolio overlap'
        end,
        'taxonomy', case
          when coalesce((taxonomy_result ->> 'available')::boolean, false)
            then taxonomy_result
        end,
        'geography', case when geography_value >= 70 then 'Target and served markets overlap' end,
        'partner_type', case when role_value >= 70 then 'Requested partner type matches' end,
        'certifications', case when certification_value >= 70 then 'Certification requirements align' end,
        'commercial', case when commercial_value >= 70 then 'Commercial capacity and preferences align' end
      )),
      jsonb_strip_nulls(jsonb_build_object(
        'profile_data', case when source_profile.profile_completeness < 60
          or target_profile.profile_completeness < 60 then 'One or both profiles are incomplete' end,
        'products', case when product_value < 35 then 'Low confirmed product overlap' end,
        'geography', case when geography_value < 35 then 'Limited confirmed market overlap' end
      )), now(), now()
    )
    on conflict (source_profile_id, target_profile_id) do update set
      match_score = excluded.match_score,
      confidence_level = excluded.confidence_level,
      product_score = excluded.product_score,
      geography_score = excluded.geography_score,
      partner_type_score = excluded.partner_type_score,
      certification_score = excluded.certification_score,
      commercial_score = excluded.commercial_score,
      reasons = excluded.reasons,
      risks = excluded.risks,
      generated_at = excluded.generated_at,
      updated_at = excluded.updated_at;
    processed := processed + 1;
  end loop;
  update public.matchmaking_profiles set last_matched_at=now(), updated_at=now()
  where id=source_profile.id;
  return jsonb_build_object('profile_id', source_profile.id,
    'profiles_processed', processed, 'generated_at', now(),
    'taxonomy_version', 'medical-taxonomy-v1');
end;
$function$;

create or replace function public.mm_build_match_explanation(
  p_match_score integer,
  p_confidence_level text,
  p_product_score integer,
  p_geography_score integer,
  p_partner_type_score integer,
  p_certification_score integer,
  p_commercial_score integer,
  p_reasons jsonb,
  p_risks jsonb
)
returns jsonb
language sql
immutable
set search_path = public, pg_temp
as $function$
  with components(key, reason_key, risk_key, label, score, weight) as (
    values
      ('product', 'products', 'products', 'Product compatibility', coalesce(p_product_score,0), 40),
      ('geography', 'geography', 'geography', 'Market compatibility', coalesce(p_geography_score,0), 20),
      ('partner_type', 'partner_type', 'partner_type', 'Company role compatibility', coalesce(p_partner_type_score,0), 15),
      ('commercial', 'commercial', 'commercial', 'Business relevance', coalesce(p_commercial_score,0), 15),
      ('certification', 'certifications', 'certifications', 'Certification compatibility', coalesce(p_certification_score,0), 10)
  ), explained as (
    select key,label,score,weight,round(score*weight/100.0,1) weighted_points,
      nullif(trim(coalesce(p_reasons->>reason_key,'')),'') reason,
      nullif(trim(coalesce(p_risks->>risk_key,'')),'') risk
    from components
  ), supported as (select * from explained where reason is not null),
  top_drivers as (
    select coalesce(jsonb_agg(jsonb_build_object(
      'key',key,'label',label,'score',score,'weight_percent',weight,
      'weighted_points',weighted_points,'reason',reason,'evidence_status','supported'
    ) order by weighted_points desc,weight desc,label),'[]'::jsonb) value
    from (select * from supported order by weighted_points desc,weight desc,label limit 3) top_three
  ), all_components as (
    select jsonb_agg(jsonb_build_object(
      'key',key,'label',label,'score',score,'weight_percent',weight,
      'weighted_points',weighted_points,
      'evidence_status',case when reason is not null then 'supported'
        when risk is not null then 'risk' else 'unknown' end,
      'reason',coalesce(reason,risk,'No explicit structured profile evidence is available for this component.')
    ) order by weight desc,label) value from explained
  )
  select jsonb_build_object(
    'version',3,
    'summary',case when (select count(*) from supported)=0 then
      'Directional score only; complete both profiles before relying on this match.'
      when coalesce(p_match_score,0)>=85 then 'Strong fit across the supported structured profile evidence.'
      when coalesce(p_match_score,0)>=70 then 'Promising fit with points that should be validated together.'
      when coalesce(p_match_score,0)>=50 then 'Possible fit; review the evidence gaps before engaging.'
      else 'Limited supported fit; review the risks before engaging.' end,
    'score',coalesce(p_match_score,0),'confidence',coalesce(p_confidence_level,'low'),
    'confidence_note',case coalesce(p_confidence_level,'low')
      when 'high' then 'Both profiles contain enough structured fields for a higher-confidence signal.'
      when 'medium' then 'The score uses partial profile data and must be validated in conversation.'
      else 'Profile evidence is limited; this score is directional, not a guarantee.' end,
    'top_reasons',(select value from top_drivers),
    'components',(select value from all_components),
    'product_evidence',coalesce(p_reasons->'taxonomy','{}'::jsonb),
    'source_reasons',coalesce(p_reasons,'{}'::jsonb),
    'risk_signals',coalesce(p_risks,'{}'::jsonb),
    'method',jsonb_build_object('product_weight_percent',40,
      'geography_weight_percent',20,'partner_type_weight_percent',15,
      'commercial_weight_percent',15,'certification_weight_percent',10,
      'taxonomy_version','medical-taxonomy-v1',
      'unknown_is_not_positive_evidence',true)
  );
$function$;

-- Tender terms are mapped only by exact canonical names or approved aliases.
-- This function never invokes AI and never invents taxonomy nodes.
create or replace function public.refresh_tender_taxonomy_mappings_v1(
  p_tender_id bigint
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $function$
declare
  tender public.tenders%rowtype;
  item jsonb;
  safe_source_term text;
  safe_lot_key text;
  matched_taxonomy_id bigint;
  matched_confidence numeric;
  matched_source text;
  inserted_count integer := 0;
begin
  if not public.is_admin()
     and coalesce(auth.jwt()->>'role','') <> 'service_role' then
    raise exception 'Taxonomy tender mapping access denied' using errcode='42501';
  end if;
  select * into tender from public.tenders where id=p_tender_id;
  if tender.id is null then raise exception 'Tender not found' using errcode='P0002'; end if;

  for item in select value from jsonb_array_elements(coalesce(tender.extracted_products,'[]'::jsonb))
  loop
    safe_source_term := trim(coalesce(
      case when jsonb_typeof(item)='object' then item->>'normalized_product_name' end,
      case when jsonb_typeof(item)='object' then item->>'product_name' end,
      case when jsonb_typeof(item)='string' then item#>>'{}' end,
      ''
    ));
    safe_lot_key := left(coalesce(case when jsonb_typeof(item)='object' then item->>'lot_number' end,''),160);
    if length(safe_source_term) < 2 then continue; end if;

    select taxonomy.id, 1::numeric, 'deterministic_name'
    into matched_taxonomy_id, matched_confidence, matched_source
    from public.medical_product_taxonomy taxonomy
    where taxonomy.is_active
      and taxonomy.normalized_name=public.normalize_medical_product_term(safe_source_term)
    limit 1;
    if matched_taxonomy_id is null then
      select alias.taxonomy_id, alias.confidence, 'verified_alias'
      into matched_taxonomy_id, matched_confidence, matched_source
      from public.medical_product_aliases alias
      join public.medical_product_taxonomy taxonomy
        on taxonomy.id=alias.taxonomy_id and taxonomy.is_active
      where alias.is_active and alias.verification_status='approved'
        and alias.confidence>=.95
        and alias.normalized_alias=public.normalize_medical_product_term(safe_source_term)
      order by alias.confidence desc limit 1;
    end if;
    if matched_taxonomy_id is not null then
      insert into public.tender_taxonomy_mappings(
        tender_id,lot_key,source_term,taxonomy_id,mapping_source,
        confidence,status,evidence,created_by
      ) values (
        p_tender_id,safe_lot_key,left(safe_source_term,1000),matched_taxonomy_id,
        matched_source,matched_confidence,'approved',
        jsonb_build_object('deterministic',true,'provider_calls',0),auth.uid()
      ) on conflict (tender_id,lot_key,normalized_source_term,taxonomy_id)
      do update set confidence=excluded.confidence,status='approved',
        evidence=excluded.evidence,updated_at=now();
      inserted_count:=inserted_count+1;
    end if;
    matched_taxonomy_id:=null; matched_confidence:=null; matched_source:=null;
  end loop;
  return jsonb_build_object('tender_id',p_tender_id,'mapped_terms',inserted_count,
    'provider_calls',0,'taxonomy_version','medical-taxonomy-v1');
end;
$function$;

