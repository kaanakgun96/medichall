    insert into public.medical_product_aliases(taxonomy_id,alias_text,source,
      confidence,verification_status,created_by)
    values(p_taxonomy_id,review.sample_term,'approved_custom',1,'approved',auth.uid())
    on conflict(normalized_alias,language_code) do update set
      taxonomy_id=excluded.taxonomy_id,verification_status='approved',is_active=true,
      confidence=1,updated_at=now();
  end if;
  update public.medical_product_taxonomy_review_queue set status=p_decision,
    suggested_taxonomy_id=p_taxonomy_id,reviewed_by=auth.uid(),reviewed_at=now()
  where id=p_review_id;
