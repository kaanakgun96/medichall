declare review public.medical_product_taxonomy_review_queue%rowtype;
begin
  if not public.is_admin() then raise exception 'Admin access required' using errcode='42501'; end if;
  if p_decision not in ('approved','rejected','keep_custom') then
    raise exception 'Invalid review decision' using errcode='22023';
  end if;
  select * into review from public.medical_product_taxonomy_review_queue where id=p_review_id for update;
  if review.id is null then raise exception 'Review item not found' using errcode='P0002'; end if;
  if p_decision='approved' and p_taxonomy_id is null then
    raise exception 'Approved terms require a taxonomy node' using errcode='22023';
