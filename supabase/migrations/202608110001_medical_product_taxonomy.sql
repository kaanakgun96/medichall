create or replace function public.medical_taxonomy_pair_score_v1(
  p_offered_taxonomy_id bigint,
  p_interested_taxonomy_id bigint
)
returns integer
language sql
stable
set search_path = public, pg_temp
as $function$
  with recursive offered_path as (
    select id, parent_id, hierarchy_level from public.medical_product_taxonomy
    where id = p_offered_taxonomy_id and is_active
    union all
    select parent.id, parent.parent_id, parent.hierarchy_level
    from public.medical_product_taxonomy parent
    join offered_path child on child.parent_id = parent.id
    where parent.is_active
  ), interested_path as (
    select id, parent_id, hierarchy_level from public.medical_product_taxonomy
    where id = p_interested_taxonomy_id and is_active
    union all
    select parent.id, parent.parent_id, parent.hierarchy_level
    from public.medical_product_taxonomy parent
    join interested_path child on child.parent_id = parent.id
    where parent.is_active
  )
  select case
    when p_offered_taxonomy_id = p_interested_taxonomy_id then 100
    when exists (select 1 from offered_path where id = p_interested_taxonomy_id)
      or exists (select 1 from interested_path where id = p_offered_taxonomy_id) then 75
    when exists (
      select 1 from public.medical_product_taxonomy offered
      join public.medical_product_taxonomy interested
        on offered.parent_id = interested.parent_id
      where offered.id = p_offered_taxonomy_id
        and interested.id = p_interested_taxonomy_id
        and offered.parent_id is not null
    ) then 25
    when exists (
      select 1 from offered_path offered
      join interested_path interested on interested.id = offered.id
      where offered.hierarchy_level = 1
    ) then 10
    else 0
  end;
$function$;

