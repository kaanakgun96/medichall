  end if;
end
$preflight$;

create or replace function public.normalize_medical_product_term(p_value text)
returns text
language sql
immutable
parallel safe
set search_path = public, pg_temp
as $function$
  select trim(regexp_replace(
    regexp_replace(lower(coalesce(p_value, '')), '([a-z0-9])[-_/]+([a-z0-9])', '\1 \2', 'g'),
    '[^a-z0-9]+', ' ', 'g'
  ));
$function$;

create or replace function public.medical_product_term_similarity(
  p_left text,
  p_right text
)
returns numeric
language sql
immutable
parallel safe
set search_path = public, pg_temp
as $function$
  with left_tokens as (
    select distinct token
    from unnest(string_to_array(public.normalize_medical_product_term(p_left), ' ')) token
    where length(token) > 1
  ),
  right_tokens as (
    select distinct token
    from unnest(string_to_array(public.normalize_medical_product_term(p_right), ' ')) token
    where length(token) > 1
  ),
  union_tokens as (
    select token from left_tokens union select token from right_tokens
  ),
  intersect_tokens as (
    select token from left_tokens intersect select token from right_tokens
  )
  select case
    when (select count(*) from union_tokens) = 0 then 0::numeric
    else round(
      (select count(*)::numeric from intersect_tokens)
      / (select count(*)::numeric from union_tokens),
      4
    )
  end;
$function$;

create table public.medical_product_taxonomy (
  id bigint generated by default as identity primary key,
  parent_id bigint references public.medical_product_taxonomy(id)
    on delete restrict,
  hierarchy_level smallint not null check (hierarchy_level between 1 and 3),
  node_type text not null check (
    node_type in ('family', 'category', 'product_type')
  ),
  canonical_name text not null check (length(trim(canonical_name)) between 2 and 160),
  normalized_name text generated always as (
    public.normalize_medical_product_term(canonical_name)
  ) stored,
  slug text not null unique check (
    slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'
  ),
  description text check (description is null or length(description) <= 1200),
  taxonomy_version text not null default 'medical-taxonomy-v1',
  is_active boolean not null default true,
  sort_order integer not null default 0,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (parent_id, normalized_name),
  check (
    (hierarchy_level = 1 and node_type = 'family' and parent_id is null)
    or (hierarchy_level = 2 and node_type = 'category' and parent_id is not null)
    or (hierarchy_level = 3 and node_type = 'product_type' and parent_id is not null)
  )
);

create index medical_product_taxonomy_parent_sort_idx
  on public.medical_product_taxonomy(parent_id, sort_order, canonical_name)
  where is_active;
create index medical_product_taxonomy_normalized_idx
  on public.medical_product_taxonomy(normalized_name)
  where is_active;

create or replace function public.validate_medical_product_taxonomy_parent()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $function$
declare
  parent_level smallint;
begin
  if new.parent_id is null then return new; end if;
  if new.parent_id = new.id then
    raise exception 'A taxonomy node cannot be its own parent'
      using errcode = '23514';
  end if;
  select hierarchy_level into parent_level
  from public.medical_product_taxonomy
  where id = new.parent_id and is_active;
  if parent_level is null or parent_level <> new.hierarchy_level - 1 then
    raise exception 'Taxonomy parent must be the active level immediately above the node'
      using errcode = '23514';
  end if;
  return new;
end;
$function$;

create trigger validate_medical_product_taxonomy_parent
before insert or update of parent_id, hierarchy_level
on public.medical_product_taxonomy
for each row execute function public.validate_medical_product_taxonomy_parent();

