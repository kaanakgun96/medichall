create or replace function public.set_company_slug()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $function$
begin
  if new.slug is null or btrim(new.slug) = '' then
    new.slug := regexp_replace(
      regexp_replace(
        translate(lower(new.name), 'çğıöşüâîû', 'cgiosuaiu'),
        '[^a-z0-9]+',
        '-',
        'g'
      ),
      '(^-+|-+$)',
      '',
      'g'
    );
    if new.slug is null or new.slug = '' then
      new.slug := 'company';
    end if;
    while exists (
      select 1
      from public.companies company
      where company.slug = new.slug
        and company.id is distinct from new.id
    )
    loop
      new.slug := new.slug || '-' || (floor(random() * 9000) + 1000)::integer;
    end loop;
  end if;
  return new;
end;
$function$;

