-- The historical dashboard script embedded a provider credential in the
-- function body.  The reconstructed contract reads a staging/production
-- operator-supplied Vault entry and becomes a safe no-op when it is absent.
create or replace function public.notify_email(
  p_to text,
  p_subject text,
  p_html text
)
returns void
language plpgsql
security definer
set search_path = public, extensions, vault, pg_temp
as $function$
declare
  resend_api_key text;
begin
  if nullif(btrim(p_to), '') is null then
    return;
  end if;

  begin
    select decrypted_secret
    into resend_api_key
    from vault.decrypted_secrets
    where name = 'medichall_resend_api_key'
    limit 1;
  exception
    when undefined_table then
      return;
  end;

  if nullif(resend_api_key, '') is null then
    return;
  end if;

  perform net.http_post(
    url := 'https://api.resend.com/emails',
    headers := jsonb_build_object(
      'Authorization', 'Bearer ' || resend_api_key,
      'Content-Type', 'application/json'
    ),
    body := jsonb_build_object(
      'from', public.mh_email_from(),
      'to', jsonb_build_array(p_to),
      'subject', p_subject,
      'html', p_html
    )
  );
exception
  when undefined_function then
    return;
end;
$function$;

create or replace function public.trg_rfq_created()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $function$
declare
  recipient_email text;
  sender_line text;
begin
  if new.company_id is not null then
    select coalesce(nullif(company.contact_email, ''), owner.email)
    into recipient_email
    from public.companies company
    left join auth.users owner on owner.id = company.owner_id
    where company.id = new.company_id;
  else
    recipient_email := public.mh_admin_email();
  end if;

  if new.user_id is not null then
    sender_line := '<b>Registered buyer</b>'
      || coalesce(' · ' || new.company, '')
      || ' — reply via the chat in your MedicHall portal.';
  else
    sender_line := new.email || coalesce(' · ' || new.company, '');
  end if;

  perform public.notify_email(
    recipient_email,
    'New quotation request — ' ||
      coalesce(new.product_name, 'general inquiry'),
    '<div style="font-family:sans-serif;line-height:1.6">'
      || '<h2 style="color:#003E52">New quotation request</h2>'
      || '<p><b>Product:</b> '
      || coalesce(new.product_name, 'General inquiry') || '</p>'
      || '<p><b>From:</b> ' || sender_line || '</p>'
      || coalesce(
        '<p style="background:#EFF6F9;padding:12px;border-radius:8px">'
        || new.message || '</p>',
        ''
      )
      || '<p><a href="' || public.mh_site_url() || '/portal.html">'
      || 'Open MedicHall Portal</a></p></div>'
  );
  return new;
end;
$function$;

create or replace function public.trg_message_created()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $function$
declare
  request_record public.rfq_requests%rowtype;
  recipient_email text;
begin
  if exists (
    select 1
    from public.rfq_messages message
    where message.rfq_id = new.rfq_id
      and message.sender_id = new.sender_id
      and message.id <> new.id
      and message.created_at > now() - interval '15 minutes'
  ) then
    return new;
  end if;

  select *
  into request_record
  from public.rfq_requests
  where id = new.rfq_id;

  if new.sender_role = 'buyer' then
    select coalesce(nullif(company.contact_email, ''), owner.email)
    into recipient_email
    from public.companies company
    left join auth.users owner on owner.id = company.owner_id
    where company.id = request_record.company_id;
  else
    select email
    into recipient_email
    from auth.users
    where id = request_record.user_id;
    recipient_email := coalesce(recipient_email, request_record.email);
  end if;

  perform public.notify_email(
    recipient_email,
    'New message on MedicHall — ' ||
      coalesce(request_record.product_name, 'your inquiry'),
    '<div style="font-family:sans-serif;line-height:1.6">'
      || '<h2 style="color:#003E52">You have a new message</h2>'
      || '<p>' || new.body || '</p>'
      || '<p><a href="' || public.mh_site_url() || '/portal.html">'
      || 'Reply on MedicHall</a></p></div>'
  );
  return new;
end;
$function$;

