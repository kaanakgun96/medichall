create or replace function public.trg_offer_created()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $function$
declare
  recipient_email text;
  product_name text;
  company_name text;
begin
  select owner.email, request.product_name
  into recipient_email, product_name
  from public.rfq_requests request
  left join auth.users owner on owner.id = request.user_id
  where request.id = new.rfq_id;

  if recipient_email is null then
    return new;
  end if;

  select name
  into company_name
  from public.companies
  where id = new.company_id;

  perform public.notify_email(
    recipient_email,
    'You received an offer — ' || coalesce(product_name, 'your inquiry'),
    '<div style="font-family:sans-serif;line-height:1.6">'
      || '<h2 style="color:#003E52">New offer received</h2>'
      || '<p><b>' || coalesce(company_name, 'A manufacturer')
      || '</b> sent an offer.</p>'
      || '<p><a href="' || public.mh_site_url() || '/portal.html#inbox">'
      || 'Compare offers on MedicHall</a></p></div>'
  );
  return new;
end;
$function$;

